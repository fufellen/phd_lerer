"""Оптические постоянные для воспроизведения статей Park 2009 и Park 2011.

Значения взяты из самих статей, чтобы расчёт опирался на те же входные данные,
что и оригинал, а не на другую редакцию табличных констант.
"""

from __future__ import annotations


def eps_from_nk(n: float, k: float) -> complex:
    """eps = (n + i k)^2. Соглашение: k > 0 у поглощающей среды, Im(eps) > 0."""
    return complex(n, k) ** 2


# --- золото ---------------------------------------------------------------
# Park 2011, рис. 1: n_Au = 0.550 - 11.4912 i при 1.55 мкм, источник Palik.
# В принятом здесь соглашении о знаке это n = 0.550, k = 11.4912.
AU_N_1550 = 0.550
AU_K_1550 = 11.4912
EPS_AU_1550 = eps_from_nk(AU_N_1550, AU_K_1550)

# Park 2008 приводит те же постоянные для 1.31 и 1.55 мкм.
EPS_AU_1310 = eps_from_nk(0.42, 9.1)

# --- полимеры -------------------------------------------------------------
# Park 2011 и Lee 2019: обкладка и центральный слой ZPU450, n = 1.450.
N_ZPU450 = 1.450
EPS_ZPU450 = complex(N_ZPU450**2, 0.0)

# Park 2009: обкладка ZPU13-430 n = 1.43, сердцевина ZPU13-440 n = 1.44.
N_ZPU13_430 = 1.43
N_ZPU13_440 = 1.44
EPS_ZPU13_430 = complex(N_ZPU13_430**2, 0.0)
EPS_ZPU13_440 = complex(N_ZPU13_440**2, 0.0)

# Park 2008: обкладка ZPU450, n = 1.451 при 1.31 мкм и 1.450 при 1.55 мкм.
EPS_ZPU450_1310 = complex(1.451**2, 0.0)

# Собственные потери полимера, измеренные в Park 2008 (дБ/см).
POLYMER_LOSS_DB_CM_1550 = 0.3
POLYMER_LOSS_DB_CM_1310 = 0.1


def k0_from_lambda(lambda_um: float) -> float:
    """Волновое число свободного пространства, мкм^-1."""
    from math import pi

    return 2.0 * pi / lambda_um
